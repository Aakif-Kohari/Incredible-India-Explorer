export function renderChaukhambaFacts(facts, container) {
    if (!container || !Array.isArray(facts)) return;

    container.innerHTML = facts.map(fact => `
        <article class="fact-card">
            <div class="fact-icon">${fact.icon}</div>
            <div class="fact-value">${fact.value}</div>
            <h3 class="fact-title">${fact.title}</h3>
            <p class="fact-desc">${fact.description}</p>
        </article>
    `).join('');
}

export function renderChaukhambaTrek(steps, container) {
    if (!container || !Array.isArray(steps)) return;

    container.innerHTML = steps.map(step => `
        <div class="trek-step-card" data-step="${step.step}">
            <div class="step-badge">Stage ${step.step}</div>
            <h3 class="step-stage">${step.stage}</h3>
            <div class="step-altitude">📍 Altitude: ${step.altitude}</div>
            <p class="step-desc">${step.description}</p>
            <div class="step-highlight">✨ <strong>Highlight:</strong> ${step.keyHighlight}</div>
        </div>
    `).join('');
}

