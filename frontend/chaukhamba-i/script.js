export function renderChaukhambaAttractions(attractions, container) {
    if (!container || !Array.isArray(attractions)) return;

    container.innerHTML = attractions.map(attr => `
        <article class="attraction-card">
            <div class="attr-header">
                <span class="attr-icon">🏔️</span>
                <div>
                    <h3 class="attr-name">${attr.name}</h3>
                    <span class="attr-dist">📍 ${attr.distance}</span>
                </div>
            </div>
            <p class="attr-desc">${attr.description}</p>
        </article>
    `).join('');
}

document.addEventListener('DOMContentLoaded', () => {
    const factsGrid = document.getElementById('facts-grid');
    const trekGrid = document.getElementById('trek-grid');
    const galleryGrid = document.getElementById('gallery-grid');
    const attractionsGrid = document.getElementById('attractions-grid');

    if (factsGrid) renderChaukhambaFacts(CHAUKHAMBA_DATA.facts, factsGrid);
    if (trekGrid) renderChaukhambaTrek(CHAUKHAMBA_DATA.trekkingInfo, trekGrid);
    if (galleryGrid) renderChaukhambaGallery(CHAUKHAMBA_DATA.gallery, galleryGrid);
    if (attractionsGrid) renderChaukhambaAttractions(CHAUKHAMBA_DATA.nearbyAttractions, attractionsGrid);
});
