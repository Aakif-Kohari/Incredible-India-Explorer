export function prefersReducedMotion() {
    return typeof window !== 'undefined'
        && typeof window.matchMedia === 'function'
        && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
}

export function initStatCounters() {
    if (typeof document === 'undefined') return;

    const counters = document.querySelectorAll('.stat-num[data-count]');
    if (!counters.length) return;

    const formatNumber = value => {
        try {
            return value.toLocaleString('en-IN');
        } catch {
            return String(value);
        }
    };

    const runCounter = el => {
        const target = parseInt(el.dataset.count, 10);
        if (Number.isNaN(target)) return;
        const prefix = el.dataset.prefix || '';
        const suffix = el.dataset.suffix || '';

        if (prefersReducedMotion() || typeof requestAnimationFrame !== 'function' || typeof performance === 'undefined') {
            el.textContent = `${prefix}${formatNumber(target)}${suffix}`;
            return;
        }

        const duration = 1600;
        const startTime = performance.now();
        const tick = now => {
            const progress = Math.min((now - startTime) / duration, 1);
            const eased = 1 - Math.pow(1 - progress, 3);
            el.textContent = `${prefix}${formatNumber(Math.round(target * eased))}${suffix}`;
            if (progress < 1) requestAnimationFrame(tick);
        };
        requestAnimationFrame(tick);
    };

    if (typeof IntersectionObserver === 'undefined') {
        counters.forEach(runCounter);
        return;
    }

    const counterObserver = new IntersectionObserver((entries, obs) => {
        entries.forEach(entry => {
            if (!entry.isIntersecting) return;
            runCounter(entry.target);
            obs.unobserve(entry.target);
        });
    }, { threshold: 0.4 });

    counters.forEach(counter => counterObserver.observe(counter));
}

export function initScrollReveal() {
    if (typeof document === 'undefined') return;

    const targets = document.querySelectorAll(
        '.reveal, .fact-card, .feature-card, .route-step-card, .gallery-card'
    );
    if (!targets.length) return;

    if (prefersReducedMotion() || typeof IntersectionObserver === 'undefined') {
        targets.forEach(el => el.classList.add('revealed'));
        return;
    }

    const observer = new IntersectionObserver((entries, obs) => {
        entries.forEach(entry => {
            if (!entry.isIntersecting) return;
            const el = entry.target;
            el.classList.add('revealed');
            el.addEventListener('transitionend', () => { el.style.transitionDelay = ''; }, { once: true });
            obs.unobserve(el);
        });
    }, { threshold: 0.15, rootMargin: '0px 0px -40px 0px' });

    targets.forEach(el => {
        const parent = el.parentElement;
        if (parent) {
            const group = Array.from(parent.children).filter(child =>
                child.classList.contains('reveal')
                || child.classList.contains('fact-card')
                || child.classList.contains('feature-card')
                || child.classList.contains('route-step-card')
                || child.classList.contains('gallery-card')
            );
            const position = Math.max(group.indexOf(el), 0);
            el.style.transitionDelay = `${Math.min(position, 7) * 90}ms`;
        }
        observer.observe(el);
    });
}

export function initLightbox(gallery = HAR_KIDUN_TREK_DATA.gallery) {
    if (typeof document === 'undefined') return null;

    const lightbox = document.getElementById('glt-lightbox');
    const grid = document.getElementById('gallery-grid');
    if (!lightbox || !grid || !Array.isArray(gallery) || !gallery.length) return null;

    const imageEl = document.getElementById('glt-lightbox-image');
    const titleEl = document.getElementById('glt-lightbox-title');
    const captionEl = document.getElementById('glt-lightbox-caption');
    const creditEl = document.getElementById('glt-lightbox-credit');
    const closeBtn = document.getElementById('glt-lightbox-close');
    const prevBtn = document.getElementById('glt-lightbox-prev');
    const nextBtn = document.getElementById('glt-lightbox-next');

    let currentIndex = 0;
    let hideTimer = null;

    const showItem = index => {
        currentIndex = (index + gallery.length) % gallery.length;
        const item = gallery[currentIndex];
        imageEl.src = item.image;
        imageEl.alt = item.title;
        titleEl.textContent = item.title;
        captionEl.textContent = item.caption;
        creditEl.textContent = item.credit;
        creditEl.href = item.sourceUrl;
    };

    const openLightbox = index => {
        clearTimeout(hideTimer);
        showItem(index);
        lightbox.hidden = false;
        if (typeof requestAnimationFrame === 'function') {
            requestAnimationFrame(() => lightbox.classList.add('open'));
        } else {
            lightbox.classList.add('open');
        }
        document.body.style.overflow = 'hidden';
        closeBtn.focus();
    };

    const closeLightbox = () => {
        lightbox.classList.remove('open');
        document.body.style.overflow = '';
        hideTimer = setTimeout(() => { lightbox.hidden = true; }, 280);
    };

    grid.addEventListener('click', event => {
        const card = event.target.closest('.gallery-card');
        if (!card || event.target.closest('.gallery-credit')) return;
        openLightbox(parseInt(card.dataset.index, 10) || 0);
    });

    grid.addEventListener('keydown', event => {
        if (event.key !== 'Enter' && event.key !== ' ') return;
        const card = event.target.closest('.gallery-card');
        if (!card) return;
        event.preventDefault();
        openLightbox(parseInt(card.dataset.index, 10) || 0);
    });

    closeBtn.addEventListener('click', closeLightbox);
    prevBtn.addEventListener('click', () => showItem(currentIndex - 1));
    nextBtn.addEventListener('click', () => showItem(currentIndex + 1));

    lightbox.addEventListener('click', event => {
        if (event.target === lightbox) closeLightbox();
    });

    document.addEventListener('keydown', event => {
        if (lightbox.hidden) return;
        if (event.key === 'Escape') closeLightbox();
        if (event.key === 'ArrowLeft') showItem(currentIndex - 1);
        if (event.key === 'ArrowRight') showItem(currentIndex + 1);
    });

    return { openLightbox, closeLightbox, showItem };
}

document.addEventListener('DOMContentLoaded', () => {
    const factsGrid = document.getElementById('facts-grid');
    const featuresGrid = document.getElementById('features-grid');
    const routesGrid = document.getElementById('routes-grid');
    const galleryGrid = document.getElementById('gallery-grid');
    const creditsList = document.getElementById('credits-list');

    if (factsGrid) renderTrekFacts(HAR_KIDUN_TREK_DATA.facts, factsGrid);
    if (featuresGrid) renderNaturalFeatures(HAR_KIDUN_TREK_DATA.naturalFeatures, featuresGrid);
    if (routesGrid) renderRouteStages(HAR_KIDUN_TREK_DATA.routeStages, routesGrid);
    if (galleryGrid) renderGallery(HAR_KIDUN_TREK_DATA.gallery, galleryGrid);
    if (creditsList) renderImageCredits(HAR_KIDUN_TREK_DATA.gallery, creditsList);

    initScrollReveal();
    initLightbox();
    initStatCounters();
});