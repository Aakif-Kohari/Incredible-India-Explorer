export function filterPMData(data, searchKeyword = '', partyCategory = 'all') {
    const query = searchKeyword.trim().toLowerCase();
    
    return data.filter(pm => {
        const matchesSearch = query === '' ||
            pm.name.toLowerCase().includes(query) ||
            pm.party.toLowerCase().includes(query) ||
            pm.start.toLowerCase().includes(query) ||
            pm.end.toLowerCase().includes(query) ||
            pm.achievements.some(a => a.toLowerCase().includes(query)) ||
            pm.events.some(e => e.toLowerCase().includes(query)) ||
            pm.facts.some(f => f.toLowerCase().includes(query));

        const matchesParty = partyCategory === 'all' || pm.partyCategory === partyCategory;

        return matchesSearch && matchesParty;
    });
}

export function getPartyBadgeClass(partyCategory) {
    switch (partyCategory) {
        case 'INC':
            return 'party-inc';
        case 'BJP':
            return 'party-bjp';
        case 'Janata Party':
            return 'party-janata';
        case 'Janata Dal':
            return 'party-dal';
        default:
            return 'party-other';
    }
}

export function calculateStats(data) {
    const totalCount = data.length;
    const uniquePersons = new Set(data.map(pm => pm.name.replace(/\s*\(\d+(?:st|nd|rd|th)?\s+Term\)/gi, '').trim())).size;
    const partyCounts = data.reduce((acc, pm) => {
        acc[pm.partyCategory] = (acc[pm.partyCategory] || 0) + 1;
        return acc;
    }, {});
    
    return {
        totalTerms: totalCount,
        uniquePrimeMinisters: uniquePersons,
        partyCounts
    };
}
