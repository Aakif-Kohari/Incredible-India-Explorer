export function filterBankingTimeline(data, searchKeyword = '', eraFilter = 'all') {
    const query = searchKeyword.trim().toLowerCase();

    return data.filter(item => {
        const matchesSearch = query === '' ||
            item.title.toLowerCase().includes(query) ||
            item.year.toLowerCase().includes(query) ||
            item.era.toLowerCase().includes(query) ||
            item.summary.toLowerCase().includes(query) ||
            item.details.toLowerCase().includes(query) ||
            item.keyImpact.toLowerCase().includes(query) ||
            item.facts.some(f => f.toLowerCase().includes(query));

        const matchesEra = eraFilter === 'all' || item.eraId === eraFilter;

        return matchesSearch && matchesEra;
    });
}

