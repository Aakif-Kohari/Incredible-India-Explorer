const FALLBACK_IMAGE = 'data:image/svg+xml;utf8,<svg xmlns="http://www.w3.org/2000/svg" width="400" height="250" viewBox="0 0 100 100"><rect width="100%" height="100%" fill="%231e293b"/><text x="50%" y="55%" fill="%2334d399" font-size="24" text-anchor="middle">🏔️</text></svg>';

function escapeHtml(value) {
    return String(value ?? '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');
}

export function renderTrekFacts(facts, container) {
    if (!container || !Array.isArray(facts)) return;

    container.innerHTML = facts.map(fact => `
        <article class="fact-card">
            <div class="fact-icon">${escapeHtml(fact.icon)}</div>
            <div class="fact-value">${escapeHtml(fact.value)}</div>
            <h3 class="fact-title">${escapeHtml(fact.title)}</h3>
            <p class="fact-desc">${escapeHtml(fact.description)}</p>
        </article>
    `).join('');
}

